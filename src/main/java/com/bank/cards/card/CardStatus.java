package com.bank.cards.card;

/**
 * Жизненный цикл карты.
 */
public enum CardStatus {
    /** Карта выпущена, но ещё не активирована клиентом. */
    NEW,
    ACTIVE,
    BLOCKED,
    /** Срок действия карты истёк. */
    EXPIRED,
    /** Карта закрыта (по заявлению клиента или после перевыпуска). */
    CLOSED
}
